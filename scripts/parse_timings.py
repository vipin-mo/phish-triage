"""How long the parsing fixes take now, against the code they replaced (reports/parse_timings.md).

    uv run python scripts/parse_timings.py    # or `make parse-timings`; $0, local, no email read

Timed on my laptop, one run each, so the numbers show the size of each fix, not Lambda's times:

- the two regular expressions that backtracked, as they were before e2e0aee and as they are now, on the crafted
  inputs the tests use (the worst of six);
- the visible-HTML reader on 100,000 unclosed `<div>` (the quadratic version was a draft that never reached git,
  so only today's time is shown);
- the Tranco domain table on a cold start: built from the pinned top-1M list, as the service did before 8c7d353,
  and loaded from the finished table the bundle ships now.
"""

from __future__ import annotations

import json
import re
import sys
import tempfile
import time
from pathlib import Path

REPORTS_DIR = Path("reports")
# The crafted inputs of tests/test_adversarial_inputs.py, about 50,000 characters each; each pattern's worst is shown.
ATTACKS = ["a-." * 50_000, "a." * 50_000, "a" * 50_000, "a@" * 50_000, "1." * 50_000, ("a" * 60 + ".") * 2_000]
# The patterns before e2e0aee (src/phish_triage/data/dedup.py, src/phish_triage/features/extract.py).
OLD_EMAIL = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
OLD_DOMAIN_IN_TEXT = re.compile(r"\b(?:https?://)?((?:[a-z0-9-]+\.)+[a-z]{2,})\b", re.IGNORECASE)


def seconds(fn) -> float:
    start = time.perf_counter()
    fn()
    return time.perf_counter() - start


def measure() -> dict:
    from phish_triage.data import dedup
    from phish_triage.features import domains, extract, html

    out: dict = {}
    for name, old, new in (
        ("email-address pattern (dedup)", OLD_EMAIL, dedup._EMAIL_RE),
        ("domain-in-text pattern (features)", OLD_DOMAIN_IN_TEXT, extract._DOMAIN_IN_TEXT),
    ):
        out[name] = {
            when: max(seconds(lambda p=p, t=t: p.findall(t)) for t in ATTACKS)
            for when, p in (("before", old), ("now", new))
        }
        print(name, out[name], file=sys.stderr)
    out["visible HTML, 100,000 unclosed <div>"] = {
        "before": None,
        "now": seconds(lambda: html.visible_html("<div>" * 100_000 + "x")),
    }
    built: list = []
    before = seconds(lambda: built.append(domains.DomainRanks.load()))
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "ranks.json"
        built[0].save(path)
        now = seconds(lambda: domains.DomainRanks.load_saved(path))
    out["Tranco domain table, cold start"] = {"before": before, "now": now, "domains": len(built[0].ranks)}
    print(out["Tranco domain table, cold start"], file=sys.stderr)
    return out


def to_markdown(r: dict) -> str:
    def cell(v: float | None) -> str:
        return "not in git" if v is None else f"{v:.2f} s" if v >= 0.1 else f"{v * 1000:.0f} ms"

    rows = [f"| {name} | {cell(v['before'])} | {cell(v['now'])} |" for name, v in r.items() if isinstance(v, dict)]
    return "\n".join(
        [
            "# The parsing fixes, timed",
            "",
            "Generated by `make parse-timings` on my laptop, one run each. The regular expressions run on the six "
            "crafted inputs of tests/test_adversarial_inputs.py (`a-.a-.a-.` and the like, 50,000 to 150,000 "
            "characters), and the worst is shown; *before* is the pattern as it was before commit e2e0aee. The "
            "domain table has "
            f"{r['Tranco domain table, cold start']['domains']:,} registered domains; *before* builds it from the "
            "Tranco list as a cold start did before commit 8c7d353, *now* loads the finished table the bundle ships. "
            "On Lambda at 2 GB the build took 7.9 s of a 19 s cold start (the function's per-step load log).",
            "",
            "| What | Before | Now |",
            "|---|---:|---:|",
            *rows,
            "",
            "The tests in tests/test_adversarial_inputs.py hold the patterns under 1 s and the HTML reader and the "
            "MIME parser under 2 s on these inputs.",
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    path = REPORTS_DIR / "parse_timings.json"
    if not (argv and argv[0] == "report"):
        path.write_text(json.dumps(measure(), indent=1) + "\n")
    text = to_markdown(json.loads(path.read_text()))
    (REPORTS_DIR / "parse_timings.md").write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
