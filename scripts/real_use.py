"""How the service has been used so far: counts only, from the live tables (reports/real_use.md); `make real-use`.

Reads the stored verdicts (verdict, stage, model version) and the feedback labels from DynamoDB, and counts the emails
I sent for retraining (the private masked file, and what is still waiting in the bucket). No email, sender, subject or
scan id is written. My own deploy checks scanned the hand-made test emails (tests/fixtures, as they are or with one
added header), so those are recognized by their SHA-256 and counted apart from real use. Stored verdicts expire
after 90 days, and an email scanned again by a newer model replaces its verdict, so this counts the emails scanned
in the last 90 days under the model that last scanned each.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

REPORT = Path("reports/real_use")
FIXTURES = Path("tests/fixtures")
# Headers my deploy checks put in front of a test email so it scanned as new (README, the deploy notes).
CHECK_HEADERS = (b"", b"X-Deploy-Check: with-newsletters-1\n", b"X-Deploy-Check: batch4\n")
# The add-on came after these models; what they last scanned are my Phase 5 deploy tests (the latency run's emails).
BEFORE_ADDON = {"with-inbox-20261103-8cd8ccfa", "with-inbox-20261104-4ee04857"}
TEST_OWNERS = {"loadtest"}  # the load test's own API key (loadtest/scan.js)


def test_scan_ids() -> set[str]:
    from phish_triage.service.store import scan_id

    return {scan_id(header + f.read_bytes()) for f in FIXTURES.glob("*.eml") for header in CHECK_HEADERS}


def scan_all(db, table: str, projection: str, names: dict | None = None) -> list[dict]:
    items, start = [], None
    while True:
        kwargs = {"TableName": table, "ProjectionExpression": projection}
        if names:
            kwargs["ExpressionAttributeNames"] = names
        if start:
            kwargs["ExclusiveStartKey"] = start
        page = db.scan(**kwargs)
        items += page.get("Items", [])
        if not (start := page.get("LastEvaluatedKey")):
            return items


def measure(db, s3=None, bucket: str | None = None) -> dict:
    from phish_triage.data.retraining import read_masked

    tests = test_scan_ids()
    items = scan_all(db, "phish-triage-verdicts", "#o, verdict", {"#o": "owner"})
    verdicts = [json.loads(i["verdict"]["S"]) | {"_owner": i.get("owner", {}).get("S")} for i in items]
    real = [
        v
        for v in verdicts
        if v["scan_id"] not in tests and v.get("model_version") not in BEFORE_ADDON and v["_owner"] not in TEST_OWNERS
    ]
    feedback = scan_all(db, "phish-triage-feedback", "scan_id, label, model_version")
    real_feedback = [f for f in feedback if f["scan_id"]["S"] not in tests]
    pulled = list(read_masked().values())
    waiting = 0
    if s3 is not None and bucket:
        waiting = sum(
            page.get("KeyCount", 0)
            for page in s3.get_paginator("list_objects_v2").paginate(Bucket=bucket, Prefix="emails/")
        )
    return {
        "as_of": datetime.now(UTC).strftime("%Y-%m-%d"),
        "emails_scanned": len(real),
        "test_emails_left_out": len(verdicts) - len(real),
        "verdicts": dict(Counter(v["verdict"] for v in real)),
        "decided_by": dict(Counter(v.get("stage") for v in real)),
        "by_model": dict(Counter(v.get("model_version") for v in real)),
        "feedback": dict(Counter(f["label"]["S"] for f in real_feedback)),
        "sent_for_retraining": {
            "pulled": dict(Counter(r["label"] for r in pulled)),
            "waiting_in_bucket": waiting,
        },
    }


def to_markdown(r: dict) -> str:
    v, fb, sent = r["verdicts"], r["feedback"], r["sent_for_retraining"]
    return "\n".join(
        [
            "# Real use so far",
            "",
            f"Generated by `make real-use` on {r['as_of']}, from the live tables: counts only. The emails are my own "
            f"Gmail's, scanned from the add-on. {r['test_emails_left_out']} test scans are left out: the hand-made "
            "test emails my deploy checks used, the emails scanned before the add-on existed (Phase 5's latency run) "
            "and the load test's. "
            "Stored verdicts expire after 90 days, and an email scanned again by a newer model replaces its verdict.",
            "",
            "| | |",
            "|---|---:|",
            f"| Emails scanned | {r['emails_scanned']} |",
            f"| Verdict: phish / review / safe | {v.get('phish', 0)} / {v.get('review', 0)} / {v.get('safe', 0)} |",
            "| Decided by | " + ", ".join(f"{k} {n}" for k, n in sorted(r["decided_by"].items())) + " |",
            "| Feedback: correct / false alarm / missed phishing | "
            f"{fb.get('correct', 0)} / {fb.get('false_alarm', 0)} / {fb.get('missed_phish', 0)} |",
            f"| Sent for retraining, used | {sent['pulled'].get('legit', 0)} as legitimate, "
            f"{sent['pulled'].get('phish', 0)} as phishing |",
            f"| Sent for retraining, waiting for the next run | {sent['waiting_in_bucket']} |",
            "",
            "| Model that last scanned them | Emails |",
            "|---|---:|",
            *[f"| `{m}` | {n} |" for m, n in sorted(r["by_model"].items())],
            "",
        ]
    )


def main() -> int:
    import boto3

    account = boto3.client("sts").get_caller_identity()["Account"]
    result = measure(boto3.client("dynamodb"), boto3.client("s3"), f"phish-triage-retraining-{account}")
    REPORT.with_suffix(".json").write_text(json.dumps(result, indent=1) + "\n")
    REPORT.with_suffix(".md").write_text(to_markdown(result))
    print(to_markdown(result))
    return 0


if __name__ == "__main__":
    sys.exit(main())
