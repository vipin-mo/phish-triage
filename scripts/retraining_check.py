"""What retraining did to the emails I sent for it (reports/retraining_check.md); `make retraining-check`.

The emails pulled by `make retrain-pull` (data/private/retraining) are scored by the bundle they were sent from and
by the retrained one, as the service scores them. They are training emails for the retrained bundle, so this is not
a test of it (reports/with_inbox.md is); it shows whether retraining changed their verdicts, and which stage
decided them. Counts only: no email, sender or subject.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

REPORT = Path("reports/retraining_check")


def main(argv: list[str]) -> int:
    from phish_triage.data.retraining import read_masked
    from phish_triage.service.bundle import BUNDLE_ROOT
    from phish_triage.service.scanner import Scanner

    before, after = argv[0], Path("infra/bundle-version").read_text().strip()
    records = list(read_masked().values())
    result = {"emails": len(records), "labels": dict(Counter(r["label"] for r in records))}
    for name, version in (("before", before), ("after", after)):
        scanner = Scanner(BUNDLE_ROOT / version, threads=4)
        scans = [(r["label"], scanner.scan_record(r)) for r in records]
        result[name] = {
            "bundle": version,
            "flagged": {
                label: sum(s.verdict == "phish" for lab, s in scans if lab == label) for label in ("phish", "legit")
            },
            "decided_by": dict(Counter(s.stage for _, s in scans)),
        }
    b, a = result["before"], result["after"]
    lines = [
        "# What retraining did to the emails I sent",
        "",
        "Generated by `make retraining-check`. The emails I sent from the add-on for retraining, scored as the service "
        "scores them by the bundle they were sent from and by the retrained one. They are in the retrained bundle's "
        "training data, so this is not a test of it (reports/with_inbox.md, *retrained*, is); it shows whether "
        "retraining changed their verdicts. Counts only.",
        "",
        f"{result['emails']} emails: {result['labels'].get('legit', 0)} sent as legitimate, "
        f"{result['labels'].get('phish', 0)} as phishing.",
        "",
        "| | Bundle | Legitimate ones flagged | Phishing ones flagged | Decided by |",
        "|---|---|---:|---:|---|",
        *[
            f"| {name} | `{v['bundle']}` | {v['flagged']['legit']} | {v['flagged']['phish']} | "
            + ", ".join(f"{k} {n}" for k, n in sorted(v["decided_by"].items()))
            + " |"
            for name, v in (("Sent from", b), ("Retrained", a))
        ],
        "",
    ]
    REPORT.with_suffix(".json").write_text(json.dumps(result, indent=1) + "\n")
    REPORT.with_suffix(".md").write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
