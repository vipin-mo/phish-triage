"""A deliberate bad deployment, to show the canary stops it (reports/canary_rollback.md).

    python scripts/rollback_check.py VERSION    # `make rollback-check VERSION=<n>`; needs the MFA session

VERSION is an older published version of the scan function, one that loads an older bundle than the one pinned in
infra/bundle-version. The script starts a CodeDeploy deployment from the `live` alias's version to it, exactly as
`scripts/canary.py` does for a real release. The smoke hook should fail it before any traffic moves (the loaded
model isn't the pinned one), CodeDeploy should mark it failed and roll it back, and the alias should stay where it
was. Only statuses and version numbers are written; no email, no account details.
"""

from __future__ import annotations

import json
import sys
from datetime import UTC, datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from canary import ALIAS, FUNCTION, deploy  # noqa: E402

REPORTS_DIR = Path("reports")


def hook_log(logs, target: str, hours: int = 2) -> dict:
    """The smoke hook's log line for `target` (`lambda_handler.before_traffic`): what it loaded and why it failed."""
    import time

    events = logs.filter_log_events(
        logGroupName="/aws/lambda/CodeDeployHook_phish-triage-smoke",
        startTime=int((time.time() - hours * 3600) * 1000),
        filterPattern='"smoke"',
    )["events"]
    lines = [json.loads(e["message"][e["message"].index("{") :]) for e in events if "{" in e["message"]]
    mine = [line for line in lines if line.get("version") == target]
    return {"loaded": mine[-1].get("model_version"), "hook_error": mine[-1].get("error")} if mine else {}


def run(lambda_client, codedeploy, target: str) -> dict:
    before = lambda_client.get_alias(FunctionName=FUNCTION, Name=ALIAS)
    status = deploy(lambda_client, codedeploy, target)
    after = lambda_client.get_alias(FunctionName=FUNCTION, Name=ALIAS)
    deployments = codedeploy.list_deployments(
        applicationName="phish-triage", deploymentGroupName="phish-triage-scan", includeOnlyStatuses=["Failed"]
    )["deployments"]
    info = codedeploy.get_deployment(deploymentId=deployments[0])["deploymentInfo"] if deployments else {}
    return {
        "date": datetime.now(UTC).date().isoformat(),
        "pinned_bundle": Path("infra/bundle-version").read_text().strip(),
        "alias_before": before["FunctionVersion"],
        "target": target,
        "status": status,
        "error": (info.get("errorInformation") or {}).get("code", ""),
        "rollback": bool(info.get("rollbackInfo")),
        "alias_after": after["FunctionVersion"],
        "weights_after": (after.get("RoutingConfig") or {}).get("AdditionalVersionWeights", {}),
    }


def to_markdown(r: dict) -> str:
    held = r["alias_after"] == r["alias_before"] and not r["weights_after"]
    return "\n".join(
        [
            "# The canary stops a bad deployment",
            "",
            f"Generated by `make rollback-check` on {r['date']}. A deliberate deployment of the scan function's "
            f"version {r['target']}, which loads an older bundle than the pinned `{r['pinned_bundle']}`, started "
            f"from version {r['alias_before']} the way a real release is.",
            "",
            "| | |",
            "|---|---|",
            f"| Deployment | {r['status']} |",
            f"| CodeDeploy's error | {r['error'] or '—'} |",
            f"| Rolled back by CodeDeploy | {'yes' if r['rollback'] else 'no'} |",
            f"| `live` alias before / after | version {r['alias_before']} / version {r['alias_after']} |",
            f"| Traffic sent to the bad version | {'none' if held else r['weights_after']} |",
            "",
            "The smoke hook (`lambda_handler.before_traffic`) failed the version before any traffic moved. Its log "
            f"line: version {r['target']} passed the two smoke emails, loaded `{r.get('loaded', 'an older bundle')}`, "
            f'and was failed as "{r.get("hook_error", "not the pinned bundle")}"; without the version check it would '
            "have gone on to the 10% window. This shows the hook's stop and CodeDeploy's rollback; the alarm-driven "
            "rollback during the 10% window hasn't had to run, and with one user that window often gets no scans.",
            "",
        ]
    )


def main(argv: list[str]) -> int:
    import boto3

    if len(argv) != 1:
        raise SystemExit("usage: rollback_check.py VERSION")
    result = run(boto3.client("lambda"), boto3.client("codedeploy"), argv[0])
    result |= hook_log(boto3.client("logs"), argv[0])
    (REPORTS_DIR / "canary_rollback.json").write_text(json.dumps(result, indent=1) + "\n")
    text = to_markdown(result)
    (REPORTS_DIR / "canary_rollback.md").write_text(text)
    print(text)
    return 0 if result["status"] == "Failed" and result["alias_after"] == result["alias_before"] else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
