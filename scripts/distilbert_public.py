"""DistilBERT's recall on the public `random` test at a fixed false-alarm rate, per trained model
(reports/distilbert_public.md); `make distilbert-public`. From the saved test predictions, no training.

Each model's DistilBERT scores every email of its split's test; this keeps the public test's 2,802 (the same emails
for every model) and reads recall off that test's curve at 1% and 0.1% false alarms, to compare the models' ranking.
The service runs at thresholds chosen on validation, which reports/with_inbox.md uses. Counts only.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

REPORT = Path("reports/distilbert_public")
MODELS = {  # the split whose DistilBERT it is -> what it is
    "random": "public data only",
    "with_inbox": "with part of my test inbox",
    "with_newsletters": "with PrivacyMail newsletters too",
    "with_normalized": "the same emails read with reader 2 (in service since 2026-11-05)",
}


def main() -> int:
    from phish_triage.evaluation import metrics, predictions

    index = {e["id"]: int(e["label"] == "phish") for e in json.loads(Path("data/interim/index.json").read_text())}
    public = json.loads(Path("data/private/test_inbox/split.json").read_text())["slices"]["public_test"]
    result = {}
    for split, what in MODELS.items():
        saved = predictions.load(split, "distilbert_head")
        scores = dict(zip(saved.test_ids, saved.test_scores, strict=True))
        ids = [i for i in public if i in scores]
        y, x = np.array([index[i] for i in ids]), np.array([scores[i] for i in ids])
        result[split] = {
            "model": what,
            "emails": len(ids),
            "recall_at_1pct_fpr": metrics.recall_at_fpr(y, x, 0.01),
            "recall_at_0.1pct_fpr": metrics.recall_at_fpr(y, x, 0.001),
        }
    lines = [
        "# DistilBERT on the public test, per model",
        "",
        "Generated by `make distilbert-public`, from each model's saved test predictions. Recall is read off the "
        "public test's own curve at a fixed false-alarm rate, to compare how the models rank phishing; the service "
        "runs at thresholds chosen on validation (reports/with_inbox.md).",
        "",
        "| DistilBERT trained on | Public test emails | Recall @ 1% false alarms | Recall @ 0.1% false alarms |",
        "|---|---:|---:|---:|",
        *[
            f"| `{split}`: {v['model']} | {v['emails']:,} | {v['recall_at_1pct_fpr']:.3f} | "
            f"{v['recall_at_0.1pct_fpr']:.3f} |"
            for split, v in result.items()
        ],
        "",
    ]
    REPORT.with_suffix(".json").write_text(json.dumps(result, indent=1) + "\n")
    REPORT.with_suffix(".md").write_text("\n".join(lines))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
