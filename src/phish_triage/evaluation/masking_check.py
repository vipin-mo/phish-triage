"""Does it matter that the service masks less than training did? (reports/masking_check.md; `make masking-check`)

    python -m phish_triage.evaluation.masking_check    # $0, local only; counts only

Training, the reports and the bundle's parity check all read emails masked with the private sources' collection
names (`data/mask.py`: my test inbox's address and PrivacyMail's collection domains, from a local file). The Lambda
image has no such file, so a live scan keeps them: a "Hi <first name>," that training only ever saw as "Hi user,".
This re-masks my inbox's test emails and PrivacyMail's held-out ones from their raw copies twice, as training did and
as the service does, scores both with the deployed bundle, and counts the emails whose masking, verdict or deciding
stage differs. Nothing but counts is written.
"""

from __future__ import annotations

import json
import re
import sys
from collections import Counter
from pathlib import Path

REPORTS_DIR = Path("reports")


def as_the_service_masks():
    """A context in which `mask_record` masks without the private collection names, as on Lambda."""
    from contextlib import contextmanager

    from phish_triage.data import mask

    @contextmanager
    def public_only():
        saved = mask._DOMAIN_RE, mask._NAME_RE
        domains = [d for d in mask.COLLECTOR_DOMAINS if d not in mask._PRIVATE_DOMAINS]
        names = [n for n in mask.COLLECTOR_NAMES if n not in mask._PRIVATE_NAMES]
        mask._DOMAIN_RE = re.compile(
            r"(?<![\w.-])(?:[\w-]+\.)*(?:" + "|".join(map(re.escape, domains)) + r")(?![\w-]|\.\w)", re.IGNORECASE
        )
        mask._NAME_RE = re.compile(r"\b(?:" + "|".join(map(re.escape, names)) + r")\b", re.IGNORECASE)
        try:
            yield
        finally:
            mask._DOMAIN_RE, mask._NAME_RE = saved

    return public_only()


def raw_tests() -> dict[str, list[dict]]:
    """The raw (parsed, unmasked) records of my inbox's test emails and PrivacyMail's held-out ones."""
    from phish_triage.data import inbox, privacymail
    from phish_triage.evaluation import privacymail as pm
    from phish_triage.service.bundle import DEPLOYED_SPLIT, load_split

    _, slices = load_split(DEPLOYED_SPLIT)
    wanted = {"inbox_test": set(slices["inbox_test"]), "privacymail_test": set(slices["privacymail_test"])}
    records, _, _ = inbox.load_inbox()
    out = {"inbox_test": [r for r in records if r["id"] in wanted["inbox_test"]]}
    saved = pm.mask_record
    pm.mask_record = lambda record: record  # the same selection as the build, without its masking
    try:
        selected, _ = pm.select(privacymail.find_zip())
    finally:
        pm.mask_record = saved
    out["privacymail_test"] = [r for r in selected if r["id"] in wanted["privacymail_test"]]
    return out


def measure() -> dict:
    from phish_triage.data.mask import mask_record
    from phish_triage.service.bundle import DEPLOYED_SPLIT, latest
    from phish_triage.service.scanner import Scanner

    scanner = Scanner(latest(split=DEPLOYED_SPLIT), threads=4)
    out: dict = {"bundle": scanner.version, "tests": {}}
    for name, records in raw_tests().items():
        counts: Counter = Counter()
        for record in records:
            trained = mask_record(record)
            with as_the_service_masks():
                live = mask_record(record)
            if json.dumps(trained, sort_keys=True) == json.dumps(live, sort_keys=True):
                counts["masked the same"] += 1
                continue
            counts["masked differently"] += 1
            a, b = scanner.scan_record(trained), scanner.scan_record(live)
            counts["flagged as trained"] += a.cascade_phish
            counts["flagged as the service masks"] += b.cascade_phish
            counts["verdict differs"] += a.verdict != b.verdict
            counts["deciding stage differs"] += a.stage != b.stage
        out["tests"][name] = {"emails": len(records), **counts}
        print(name, out["tests"][name], file=sys.stderr)
    return out


def to_markdown(r: dict) -> str:
    keys = (
        "masked differently",
        "flagged as trained",
        "flagged as the service masks",
        "verdict differs",
        "deciding stage differs",
    )
    names = {"inbox_test": "My inbox's test senders", "privacymail_test": "PrivacyMail held-out websites"}
    lines = [
        "# Masking at scan time vs in training",
        "",
        "Generated by `make masking-check`. Training masked the private sources' collection names (my test inbox's "
        "address, PrivacyMail's collection domains); the service can't, because the names stay on my laptop. These "
        "are the deployed bundle's verdicts "
        f"(`{r['bundle']}`) on the same raw test emails masked both ways. Counts only; *flagged* counts only the "
        "emails masked differently.",
        "",
        "| | Emails | " + " | ".join(k.capitalize() for k in keys) + " |",
        "|---|---:|" + "---:|" * len(keys),
        *[
            f"| {names[n]} | {v['emails']:,} | " + " | ".join(f"{v.get(k, 0):,}" for k in keys) + " |"
            for n, v in r["tests"].items()
        ],
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    path = REPORTS_DIR / "masking_check.json"
    if not (argv and argv[0] == "report"):
        path.write_text(json.dumps(measure(), indent=1) + "\n")
    text = to_markdown(json.loads(path.read_text()))
    (REPORTS_DIR / "masking_check.md").write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
