"""Would sending own-domain-signed emails to review cut false alarms without hiding phishing? (reports/own_domain.md)

    python -m phish_triage.evaluation.own_domain      # $0, local; the private tests give counts only

The rule (`triage.own_domain_signed`, set before this ran): an email the cascade flags goes to review instead of being
marked phishing when the sender check passes with a DKIM signature from the From domain itself, raises no warning,
the domain is in the Tranco top 100,000, and the email has links, all on that domain. Measured with the deployed
bundle and with the reader-2 candidate (`defence.py`, setup d), on the same tests as the defence, and on the emails I
sent for retraining (training emails for both, so they show what the rule does to them, not a test).
"""

from __future__ import annotations

import json
import multiprocessing
import sys
from pathlib import Path

REPORTS_DIR = Path("reports")
SETUPS = ("deployed", "d_normalized")
ROWS = {
    "public_phish": "Public test, phishing",
    "phish_2026": "2026 phishing",
    "newsletter_like_phish": "Newsletter-like phishing",
    "public_legit": "Public test, legitimate",
    "inbox_test": "My inbox's test senders",
    "privacymail_test": "PrivacyMail held-out websites",
    "sent_for_retraining": "Emails I sent for retraining (trained on)",
}


def measure_setup(setup: str) -> dict:
    from phish_triage.data.retraining import read_masked
    from phish_triage.evaluation.defence import scanner_for, test_sets
    from phish_triage.service.triage import own_domain_signed

    scanner = scanner_for(setup)
    sets, records = test_sets()
    sent = read_masked()
    sets["sent_for_retraining"], records = list(sent), records | sent
    out = {"bundle": scanner.version}
    for name, ids in sets.items():
        flagged = [i for i in ids if scanner.scan_record(records[i]).cascade_phish]
        moved = sum(own_domain_signed(records[i], scanner.ranks) for i in flagged)
        out[name] = {"emails": len(ids), "flagged": len(flagged), "to_review": moved}
        print(f"{setup} {name}: {out[name]}", file=sys.stderr)
    return out


def to_markdown(r: dict) -> str:
    from phish_triage.evaluation.defence import SETUP_NAMES

    lines = [
        "# The own-domain rule: flagged, but signed by its own well-known domain",
        "",
        "Generated by `make own-domain`. The rule (set before this ran): an email the cascade flags goes to review "
        "instead of being marked phishing when the sender check passes with a DKIM signature from the From domain "
        "itself, raises no warning, the domain is in the Tranco top 100,000, and the email has links, all on that "
        "domain. *Moved to review* counts flagged emails the rule would move; for phishing that is phishing no longer "
        "marked phishing (a person still sees it), for legitimate mail a false alarm made milder. The private tests "
        "are scored on my laptop; only counts are shown.",
        "",
        "| Test | Emails | " + " | ".join(f"{SETUP_NAMES[s]}: flagged, moved to review" for s in r) + " |",
        "|---|---:|" + "---:|" * len(r),
    ]
    first = next(iter(r.values()))
    for key, label in ROWS.items():
        cells = [f"{r[s][key]['flagged']:,}, {r[s][key]['to_review']}" for s in r]
        lines.append(f"| {label} | {first[key]['emails']:,} | " + " | ".join(cells) + " |")
    return "\n".join([*lines, ""])


def main() -> int:
    with multiprocessing.get_context("spawn").Pool(len(SETUPS)) as pool:
        result = dict(zip(SETUPS, pool.map(measure_setup, SETUPS), strict=True))
    REPORTS_DIR.mkdir(exist_ok=True)
    (REPORTS_DIR / "own_domain.json").write_text(json.dumps(result, indent=1) + "\n")
    text = to_markdown(result)
    (REPORTS_DIR / "own_domain.md").write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
