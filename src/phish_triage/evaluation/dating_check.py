"""How often does the date the splits use disagree with the receiving server's? (reports/dating_check.md)

    python -m phish_triage.evaluation.dating_check    # or `make dating-check`; $0, public data only, counts only

Every email is dated by its earliest Received hop (`parse.message_date`): the bottom Received header, the first server
on the way. That hop can be written by the sender, so a phisher could forge it; the topmost one is added by the
server that received the email for the collection (the honeypot's or the list's), which the sender can't write
(docs/THREAT_MODEL.md). This counts, per source, the kept emails whose two dates fall in different months, and those
more than 31 days apart, so it shows whether month matching and the time splits could rest on forged dates.
"""

from __future__ import annotations

import gzip
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPORTS_DIR = Path("reports")


def hop_dates(headers: list) -> tuple | None:
    """(earliest hop's date, topmost hop's date) when both parse and are plausible, else None."""
    from phish_triage.data.parse import EARLIEST_PLAUSIBLE, _parse_date

    dates = []
    for name, value in headers:
        if name.lower() == "received":
            when = _parse_date(value.rpartition(";")[2])
            dates.append(when if when and when >= EARLIEST_PLAUSIBLE else None)
    if len(dates) < 2 or dates[0] is None or dates[-1] is None:
        return None
    return dates[-1], dates[0]


def measure() -> dict:
    from phish_triage.data.build import INTERIM_DIR
    from phish_triage.data.records import RAW_RECORDS

    kept = {e["id"] for e in json.loads((INTERIM_DIR / "index.json").read_text()) if e["kept"]}
    counts: defaultdict[str, Counter] = defaultdict(Counter)
    with gzip.open(RAW_RECORDS, "rt", encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            if r["id"] not in kept:
                continue
            c = counts[f"{r['source']} ({r['label']})"]
            c["emails"] += 1
            if (pair := hop_dates(r.get("headers") or [])) is None:
                continue
            earliest, top = pair
            c["two dated hops"] += 1
            c["different month"] += earliest.strftime("%Y-%m") != top.strftime("%Y-%m")
            c["over 31 days apart"] += abs((top - earliest).total_seconds()) > 31 * 86_400
    return {"sources": {k: dict(v) for k, v in sorted(counts.items())}}


def to_markdown(r: dict) -> str:
    def share(v: dict, key: str) -> str:
        n = v.get("two dated hops", 0)
        if not n:
            return "—"
        k = v.get(key, 0)
        return f"{k:,} ({'under 0.1%' if 0 < k / n < 0.001 else f'{k / n:.1%}'})"

    return "\n".join(
        [
            "# The earliest Received date against the topmost one",
            "",
            "Generated by `make dating-check`, on the public sources' kept emails. The splits date an email by its "
            "earliest Received hop, which the sender can write; the topmost is the collecting server's own. Counted "
            "over the emails with at least two dated hops.",
            "",
            "| Source | Emails | Two dated hops | Different month | Over 31 days apart |",
            "|---|---:|---:|---:|---:|",
            *[
                f"| {s} | {v['emails']:,} | {v.get('two dated hops', 0):,} | {share(v, 'different month')} | "
                f"{share(v, 'over 31 days apart')} |"
                for s, v in r["sources"].items()
            ],
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    path = REPORTS_DIR / "dating_check.json"
    if not (argv and argv[0] == "report"):
        path.write_text(json.dumps(measure(), indent=1) + "\n")
    text = to_markdown(json.loads(path.read_text()))
    (REPORTS_DIR / "dating_check.md").write_text(text)
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
